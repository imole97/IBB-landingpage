/**
 * Generates src/lib/emailImages.ts — the images the emails carry with them.
 *
 * Emails used to load their images from the live site. That only works once
 * the site is deployed, and never from a local build, whose address
 * (localhost) no inbox can reach. So the images are attached to each email
 * instead and referenced by content ID (`cid:`). To be attached they have
 * to be in the server bundle, so they're inlined here as base64 rather than
 * read from public/ at runtime, where a serverless function may not find
 * them.
 *
 * Run: npm run emails:images   (after changing any of the files below)
 */
import { readFile, writeFile } from "node:fs/promises";

const OUT = "src/lib/emailImages.ts";

/** cid → file. The cid is what the HTML references: src="cid:ibb-logo". */
const IMAGES = {
  "ibb-logo": "public/logo.png",
  "ibb-thank-you": "public/email/thank-you.png",
  "ibb-instagram": "public/email/instagram.png",
};

const entries = await Promise.all(
  Object.entries(IMAGES).map(async ([cid, path]) => {
    const base64 = (await readFile(path)).toString("base64");
    return `  "${cid}": {\n    filename: "${path.split("/").pop()}",\n    base64:\n      "${base64}",\n  },`;
  }),
);

await writeFile(
  OUT,
  `// Generated by scripts/make-email-images.mjs — do not edit by hand.
// Run \`npm run emails:images\` after changing an image it lists.

export const emailImages = {
${entries.join("\n")}
} as const;

export type EmailImage = keyof typeof emailImages;
`,
);
console.log(OUT);
